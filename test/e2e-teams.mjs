// Team mode e2e (server with DEBUG_HOOKS=1): node test/e2e-teams.mjs [base] [outDir]
import { chromium } from 'playwright';
const base = process.argv[2] || 'http://localhost:2567', out = process.argv[3] || '.';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const errors = []; const wait = (ms) => new Promise(r => setTimeout(r, ms)); const log = (...a) => console.log(...a);
const p = await (await browser.newContext({ viewport: { width: 1280, height: 800 } })).newPage();
p.on('pageerror', e => errors.push(e.message));
await p.goto(base); await p.fill('#gate-name', 'Teamy'); await p.fill('#gate-email', `qa-team-${Date.now()}@example.com`); await p.click('#gate-form button');
await p.waitForSelector('#home:not(.hidden)');
await p.click('#btn-solo');
await p.waitForFunction(() => window.__sm.snap?.players?.length >= 2);
await p.click('#crew button[data-crew="6"]');
await p.waitForFunction(() => window.__sm.snap.players.filter(x => !x.spectator).length === 6, null, { timeout: 5000 }).catch(() => errors.push('crew of 6 did not fill'));
await p.click('#teams button[data-teams="3"]');
await p.waitForFunction(() => window.__sm.snap.teamN === 3, null, { timeout: 4000 }).catch(() => errors.push('3 teams did not turn on'));
await p.waitForSelector('.tcol', { timeout: 4000 }).catch(() => errors.push('no team columns in the lobby'));
log('team columns:', await p.locator('.tcol').count());
const myTeam = await p.evaluate(() => window.__sm.snap.players.find(x => x.id === window.__sm.myId).team);
const other = myTeam === 1 ? 2 : 1;
await p.click(`.tjoin[data-team="${other}"]`);
await p.waitForFunction((t) => window.__sm.snap.players.find(x => x.id === window.__sm.myId).team === t, other, { timeout: 4000 }).catch(() => errors.push('could not switch teams'));
const sizes = await p.evaluate(() => [1, 2, 3].map(t => window.__sm.snap.players.filter(x => x.team === t).length));
log('switched to', other, 'sizes', sizes.join('/'));
if (sizes.some(n => n !== 2)) errors.push('teams not even: ' + sizes);
await p.locator('#lobby-players').scrollIntoViewIfNeeded();
await p.screenshot({ path: `${out}/tm01-lobby.png` });
await p.click('#btn-start');
await p.waitForFunction(() => window.__sm.snap?.phase === 'playing', null, { timeout: 8000 });
await wait(4000);
const hud = await p.locator('#scoreboard .sb.team').count();
log('team totals in HUD:', hud);
if (hud !== 3) errors.push('HUD should show 3 team totals');
await p.screenshot({ path: `${out}/tm02-hud.png` });
await p.evaluate(() => window.__sm.send('debug_end'));
await p.waitForFunction(() => window.__sm.snap?.phase === 'results', null, { timeout: 20000 }).catch(() => errors.push('no results'));
await wait(1200);
const banner = await p.textContent('#res-winner');
log('results:', banner.trim().slice(0, 80));
if (!/TEAM WINS|TIE/.test(banner)) errors.push('results should name the winning team');
await p.screenshot({ path: `${out}/tm03-results.png` });
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'TEAMS E2E PASS');
await browser.close(); process.exit(errors.length ? 1 : 0);
